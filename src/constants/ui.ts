/**
 * 화면 가운데 상자 — **좌우 여백 16px · 최대폭 1280px**.
 *
 * 헤더와 본문이 **같은 값**을 써야 로고 왼쪽 끝과 본문 왼쪽 끝이 한 줄로 선다(#963).
 * 예전에는 값이 셋으로 갈려 있었다.
 *
 *   헤더    px-4 lg:px-3.5   16 → 1024 부터 14
 *   홈 본문  px-4 md:px-8     16 → 768 부터 32
 *   그 밖    px-4 · px-lg     16                 ← 이 값이 제일 많아 여기에 맞췄다
 *
 * 그래서 1024px 에서 로고 14 · 본문 32 로 **18px 이 어긋나 보였다.**
 *
 * ⚠️ **새 화면을 만들 때 `px-*` 를 손으로 적지 말고 이것을 쓴다.** 하나만 달라도
 *    그 화면에서만 어긋나고, 눈으로는 잘 안 보여서 한참 뒤에 발견된다.
 *
 * ⚠️ 히어로(`HomeHero.tsx`)만 예외로 `lg:px-4` 를 직접 적는다. 좁은 화면에서는
 *    배경이 화면 끝까지 차야 해서 여백을 1024 부터만 준다. **값은 여기와 같아야 한다.**
 */

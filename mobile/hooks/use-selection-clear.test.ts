import { 탭인가 } from './use-selection-clear';

// 「짧게 눌렀다 떼면 탭 · 길게 누르면 글자를 고르는 중」이라는 판단만 여기서 지킨다.
//
// ⚠️ **실제로 선택이 풀리는지는 시험이 못 본다.** 안드로이드의 글자 선택은 네이티브
//    TextView 가 쥐고 있어 jest 에 없다. 실기기로 봐야 한다(mobile/AGENTS.md).

it('짧게 눌렀다 떼면 탭이다', () => {
  expect(탭인가(1000, 1100)).toBe(true);
  expect(탭인가(1000, 1299)).toBe(true);
});

it('오래 누르면 탭이 아니다 — 글자를 고르는 중이다', () => {
  // 안드로이드의 꾹 누르기는 500ms 안팎이다. 그보다 앞에서 잘라야 선택을 안 방해한다.
  expect(탭인가(1000, 1300)).toBe(false);
  expect(탭인가(1000, 1600)).toBe(false);
});
